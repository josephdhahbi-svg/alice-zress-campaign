'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {normalizeLedgerEvent,projectLedgerStory}=require('./ledgerStoryAdapter');
const {initialWorld,reduceWorld}=require('./worldReducer');
const opts={profileId:'alice-zress',sceneId:'U01_SILVER_COURIER'};
const e={eventId:'EV_1',commandId:'CMD_1',sceneId:opts.sceneId,type:'HEROIC_CHOICE_COMMITTED',revision:1,choiceId:'NEUTRAL_GOOD'};
test('normalizes committed choice',()=>assert.equal(normalizeLedgerEvent(e,opts.profileId).data.choiceId,'NEUTRAL_GOOD'));
test('normalizes outbox envelope',()=>assert.equal(normalizeLedgerEvent({event:e},opts.profileId).worldTick,1));
test('projects chosen action',()=>assert.equal(projectLedgerStory([e],opts).beats[0].choiceId,'NEUTRAL_GOOD'));
test('matches world reducer history',()=>assert.equal(reduceWorld(initialWorld(),e).history[0].choiceId,projectLedgerStory([e],opts).beats[0].choiceId));
test('does not invent dialogue',()=>assert.equal(projectLedgerStory([e],opts).beats[0].dialogue,null));
test('does not invent artwork',()=>assert.equal(projectLedgerStory([e],opts).beats[0].visualAssetId,null));
test('does not mutate events',()=>{const before=JSON.stringify(e);projectLedgerStory([e],opts);assert.equal(JSON.stringify(e),before)});
test('rejects unsupported type',()=>assert.throws(()=>normalizeLedgerEvent({...e,type:'ITEM_GRANTED'},opts.profileId)));
test('rejects missing revision',()=>assert.throws(()=>normalizeLedgerEvent({...e,revision:null},opts.profileId)));
test('rejects duplicate IDs',()=>assert.throws(()=>projectLedgerStory([e,e],opts)));
test('rejects reversed order',()=>assert.throws(()=>projectLedgerStory([{...e,eventId:'EV_2',revision:2},e],opts)));
test('rejects invalid choice',()=>assert.throws(()=>projectLedgerStory([{...e,choiceId:'INVALID'}],opts)));
test('rejects invalid input',()=>assert.throws(()=>projectLedgerStory([null],opts)));
